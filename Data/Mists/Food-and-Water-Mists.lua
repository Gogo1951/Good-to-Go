How We Got the Data

Last Validated
	2026-11-03, Mists of Pandaria Classic 5.5.4.70631

Notes
	- Every food and drink this client knows that restores health or mana while seated, read by the item cache (Features/Macros-for-Consumables/Item-Cache.lua) for the Food and Water macros and the buff-food choices. The family is the items whose use spell is on the food (11) or drink (59) cooldown category, plus the few on no category whose spell says "Must remain seated".
	- Buff Food is 1 when eating gives a Well Fed buff: the spell applies one after a delay (a periodic trigger aura), raises a stat outright, or its text says "well fed".
	- Food % and Water % are percent of health or mana per second (100% over 20 sec is 5), from the percent auras. Food Amount and Water Amount are the whole restore over the meal: the per-5-second amount times the duration in seconds over 5, which is how the client's own tooltips compute it ($o1 for health, ${$m2/5*$d} for mana). A drink's amount is its periodic-dummy effect (the second effect, the one the tooltip reads), not the flat regen aura beside it, which some drinks also fill.
	- From Cataclysm on most amounts are scaled: the effect's coefficient times the SpellScaling game table (gametables/spellscaling.txt, file 1391660) at the spell's MaxScalingLevel. That is what a character at or above that level gets. A few foods are usable up to five levels before their scaling cap and give a little less to a character still below it; the ranking only compares items, so the order holds.
	- Allowed Zones are uiMapIDs, from each spell's required area group: 92 Warsong Gulch, 93 Arathi Basin, 338 Molten Front (the Eternal fruits), 379 Kun-Lai Summit (Grummlecake).
	- Arena (column 7): 1 = offered ONLY inside a PvP Arena (Star's Tears, Star's Lament, Star's Sorrow, hand-listed). 2 = a conjured item the client also flags usable in arenas (item flags 0x2 and 0x200000). Many ordinary Cataclysm and Pandaria drinks carry the arena flag too but are not conjured; the table has no value for "usable everywhere, arena included", so they carry none and are never offered inside one. The Eternal fruits are conjured but lack the arena flag, so they carry none either.
	- Left out on purpose, as on the other clients: Scorpid Surprise (5473) and Riverpaw Tea Leaf (1401, Green Tea Leaf on older clients), oddballs on the food cooldown; Blessed Sunfruit Juice (13813) and Bottled Alterac Spring Water (19318), whose Well Fed buffs are recognized through ns.WELL_FED_BUFF_IDS; Skullfish Soup (33825); items that share the cooldown but restore nothing (alcohol, Deviate fish, most holiday novelties); feasts that place a table.
	- Also left out: the Pilgrim's Bounty dishes (44836-44840), Bread of the Dead (46691) and Winter Veil Cookie (21254), which scale with the eater's level from 1 to 85, so no fixed amount describes them; Lifegiving Seed (63122), a disguise with a restore attached; Tradeskill Food (85577), a placeholder; and items named Deprecated, UNUSED, OLD, TEST, DEBUG or [PH].
	- Every row has a source: a drop, vendor or quest reward in QuestieDB's MoP item table, or a spell that creates it. Items with neither are left out, among them the pre-Cataclysm conjured breads and waters (Conjure Refreshment replaced the spells that made them), Darkshore Grouper (12238) and Fizzy Energy Drink (23176).

