"""
Builds Data/{Game}/Rank-Watch-Abilities-{Game}.lua from Rank Sentinel's ability tables.

Rank Sentinel (MIT, Copyright (c) 2021 Gogo1951) keeps its tracked abilities in AbilityData/Classic.lua and
AbilityData/TBC.lua, generated by its own AbilityData/Build.py from the "Classic Abilities" and "TBC Abilities"
sheets. Those tables carry no class and no names, so this script reads each flavor's own
Trainer-Spells-{Game}.lua to put every ability under its class, name it in the trailing comment, and take its
learn levels from the trainer rows, which the Enhanced Spellbook's What's Next reads too. A rank the trainer
rows don't list keeps Rank Sentinel's level, and the script says so.

Run from the add-on root, with a Rank Sentinel checkout beside it or named by --source:

    python3 Tools/Build-Rank-Watch-Abilities.py --source ../Rank-Sentinel

The Mists, Wrath and Mainline folders get an empty table (Mists has no ranks; Wrath and Mainline have no TOC).
"""

import argparse
import os
import re
import sys

# Good to Go flavor folder -> Rank Sentinel ability table it is built from.
FLAVORS = {
    "Vanilla": "Classic.lua",
    "Discovery": "Classic.lua",
    "Camelot": "Classic.lua",
    "TBC": "TBC.lua",
}
EMPTY_FLAVORS = ["Mists", "Wrath", "Mainline"]

CLASS_ORDER = ["DRUID", "HUNTER", "MAGE", "PALADIN", "PRIEST", "ROGUE", "SHAMAN", "WARLOCK", "WARRIOR"]

ROW = re.compile(r"\[(\d+)\]\s*=\s*\{\s*Rank\s*=\s*(\d+),\s*Level\s*=\s*(\d+),\s*AbilityGroup\s*=\s*(\d+)")
TRAINER_CLASS = re.compile(r"^\t([A-Z]+) = \{")
TRAINER_ROW = re.compile(r"^\t\t\{ level = (\d+), id = (\d+).*\},\s*--\s*(.+)$")
DISCOVERY_GUARD = {
    "Vanilla": "if ns.IS_DISCOVERY then\n\treturn\nend\n\n",
    "Discovery": "if not ns.IS_DISCOVERY then\n\treturn\nend\n\n",
}


def read_rank_sentinel(path):
    groups = {}
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            match = ROW.search(line)
            if match:
                spell, rank, level, group = (int(value) for value in match.groups())
                groups.setdefault(group, []).append({"id": spell, "rank": rank, "level": level})
    return groups


def read_trainer(path):
    rows = {}
    current = None
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            header = TRAINER_CLASS.match(line)
            if header:
                current = header.group(1)
                continue
            match = TRAINER_ROW.search(line)
            if match and current:
                level, spell, name = int(match.group(1)), int(match.group(2)), match.group(3).strip()
                rows.setdefault(spell, {"class": current, "level": level, "name": name})
    return rows


def read_class_lists(path):
    """Spell id -> class and name from Class-Spell-Lists-{Game}.lua, for spells no trainer teaches (books, talents)."""
    rows = {}
    current = None
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            header = TRAINER_CLASS.match(line)
            if header:
                current = header.group(1)
                continue
            if "--" not in line or not current:
                continue
            code, name = line.split("--", 1)
            if "=" in code:
                continue
            for spell in re.findall(r"\d+", code):
                rows.setdefault(int(spell), {"class": current, "name": name.strip()})
    return rows


def build(flavor, source, root):
    trainer_path = os.path.join(root, "Data", flavor, "Trainer-Spells-%s.lua" % flavor)
    trainer = read_trainer(trainer_path)
    class_lists = read_class_lists(os.path.join(root, "Data", flavor, "Class-Spell-Lists-%s.lua" % flavor))
    # A spell this flavor's lists don't name (WoW Forever's lists are its own) is placed by the other flavors' lists.
    others = {}
    for other in FLAVORS:
        if other != flavor:
            for table in (
                read_trainer(os.path.join(root, "Data", other, "Trainer-Spells-%s.lua" % other)),
                read_class_lists(os.path.join(root, "Data", other, "Class-Spell-Lists-%s.lua" % other)),
            ):
                for spell, info in table.items():
                    others.setdefault(spell, info)
    groups = read_rank_sentinel(os.path.join(source, "AbilityData", FLAVORS[flavor]))
    by_class = {}
    notes = []
    for group in sorted(groups):
        ranks = sorted(groups[group], key=lambda row: (row["rank"], row["level"]))
        known = [trainer[row["id"]] for row in ranks if row["id"] in trainer]
        known += [class_lists[row["id"]] for row in ranks if row["id"] in class_lists]
        known += [others[row["id"]] for row in ranks if row["id"] in others]
        if not known:
            notes.append("no trainer or class list row for any rank of group %d (%s); left out" % (group, ranks[0]["id"]))
            continue
        for row in ranks:
            info = trainer.get(row["id"])
            if info is None:
                notes.append("%s: %d has no trainer row; kept Rank Sentinel's level %d" % (known[0]["name"], row["id"], row["level"]))
            elif info["level"] != row["level"]:
                notes.append("%s Rank %d: trainer level %d over Rank Sentinel's %d" % (info["name"], row["rank"], info["level"], row["level"]))
                row["level"] = info["level"]
        by_class.setdefault(known[0]["class"], []).append({"name": known[0]["name"], "ranks": ranks})
    return by_class, notes


def write(flavor, by_class, source_file, root):
    path = os.path.join(root, "Data", flavor, "Rank-Watch-Abilities-%s.lua" % flavor)
    out = ["local _, ns = ...\n\n", DISCOVERY_GUARD.get(flavor, "")]
    out.append("-- [classToken] = { { { id, rank, level }, ... }, ... }, -- each ability's ranks, lowest first\n")
    if not by_class:
        out.append("ns.RANK_WATCH_ABILITIES = {}\n")
    else:
        out.append("ns.RANK_WATCH_ABILITIES = {\n")
        for class_token in CLASS_ORDER:
            abilities = by_class.get(class_token)
            if not abilities:
                continue
            out.append("\t%s = {\n" % class_token)
            for ability in sorted(abilities, key=lambda entry: entry["name"]):
                out.append("\t\t{\n")
                for row in ability["ranks"]:
                    out.append("\t\t\t{ id = %d, rank = %d, level = %d },\n" % (row["id"], row["rank"], row["level"]))
                out.append("\t\t}, -- %s\n" % ability["name"])
            out.append("\t},\n")
        out.append("}\n")
    out.append(HOW_WE_GOT_THE_DATA[source_file is not None].format(source=source_file, flavor=flavor))
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("".join(out))
    return path


HOW_WE_GOT_THE_DATA = {
    True: """
--[[
How We Got the Data

Last Validated
	Never.

Notes
	- Built by Tools/Build-Rank-Watch-Abilities.py from Rank Sentinel's AbilityData/{source} (MIT, Copyright (c) 2021 Gogo1951), the abilities its "Include" column keeps: heals and other spells players lower on purpose are left out there, not here.
	- Each ability sits under the class whose Trainer-Spells-{flavor}.lua row teaches it, named by that row's comment, and takes the trainer row's learn level where the two disagree.
	- rank is the spell's own rank number, so an ability whose first ranks Rank Sentinel leaves out starts above 1.
	- Features/Rank-Watch/Rank-Watch-Lookups.lua joins abilities that ns.SPELL_GROUPS lists as one group (Demon Skin, then Demon Armor) into one ladder, ordered by learn level.

SQL (CMaNGOS)
	None.

Wowhead
	None.

wago.tools
	None.

QuestieDB
	None.
]]
""",
    False: """
--[[
How We Got the Data

Last Validated
	Never.

Notes
	- Empty: Rank Watch reports a rank lower than the caster could have, and this flavor has no ranks to compare, or no TOC lists this folder.

SQL (CMaNGOS)
	None.

Wowhead
	None.

wago.tools
	None.

QuestieDB
	None.
]]
""",
}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", default=os.path.join("..", "Rank-Sentinel"))
    args = parser.parse_args()
    root = os.getcwd()
    if not os.path.isdir(os.path.join(root, "Data")):
        sys.exit("Run from the Good to Go add-on root.")
    for flavor in FLAVORS:
        by_class, notes = build(flavor, args.source, root)
        path = write(flavor, by_class, FLAVORS[flavor], root)
        count = sum(len(abilities) for abilities in by_class.values())
        print("%s: %d abilities -> %s" % (flavor, count, path))
        for note in notes:
            print("  " + note)
    for flavor in EMPTY_FLAVORS:
        print("%s: empty -> %s" % (flavor, write(flavor, {}, None, root)))


if __name__ == "__main__":
    main()
